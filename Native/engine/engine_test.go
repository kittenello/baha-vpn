package engine

import (
    "encoding/json"
    "os"
    "path/filepath"
    "testing"
)

// Fixtures are emitted by the Swift tests, so the native core validates the actual client output.
func TestClientGeneratedConfigurations(t *testing.T) {
    root := os.Getenv("BAHA_FIXTURES")
    if root == "" { t.Skip("fixtures are generated by swift test in CI") }
    files, err := filepath.Glob(filepath.Join(root, "*.json"))
    if err != nil || len(files) < 6 { t.Fatal("missing protocol fixtures") }
    for _, file := range files {
        t.Run(filepath.Base(file), func(t *testing.T) {
            data, err := os.ReadFile(file)
            if err != nil { t.Fatal(err) }
            cfg, err := Config(string(data))
            if err != nil { t.Fatal(err) }
            if len(cfg.Outbound) == 0 { t.Fatal("missing outbound") }
            var object map[string]any
            if err := json.Unmarshal(data, &object); err != nil { t.Fatal(err) }
        })
    }
}
